        '            package="rviz2",\n' ...
        '            executable="rviz2",\n' ...
        '            arguments=["-d", "%s"]\n' ...
        '        )\n' ...
        '    ])\n'], urdfPath, rvizCfgPath);
    fPy = fopen(launchPath, 'w'); fwrite(fPy, launchPy); fclose(fPy);

    system('bash -c "killall -9 rviz2 robot_state_publisher joint_state_publisher_gui 2>/dev/null"');
    launchCmd = sprintf('bash -c "unset LD_LIBRARY_PATH; unset QT_PLUGIN_PATH; source /opt/ros/jazzy/setup.bash; ros2 launch %s" &', launchPath);
    fprintf('Launching RViz2 and Joint State Sliders...\n');
    system(launchCmd);
end
