        '  </joint>\n' ...
        '  <link name="link_3">\n' ...
        '    <visual>\n' ...
        '      <origin xyz="-0.1750 0 0" rpy="0 1.5708 0"/>\n' ...
        '      <geometry><cylinder length="0.3500" radius="0.0500"/></geometry>\n' ...
        '    </visual>\n' ...
        '  </link>\n\n' ...
        '  <joint name="joint_4" type="revolute">\n' ...
        '    <parent link="link_3"/>\n' ...
        '    <child link="link_4"/>\n' ...
        '    <origin xyz="0.3500 0.0000 0.0000" rpy="0 0 0"/>\n' ...
